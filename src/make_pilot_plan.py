"""Write configs/pilot.yaml (part 6b, item 9) from metadata only.

Rule: among the development datasets (data/split/development.txt), compute the size score
n_samples x min(200, n_features), with n and p after the data-handling rules (from data/meta/audit.csv
and data/meta/data_handling_rules.json, as in src/make_split.py; no parquet file is opened). Sort
ascending (ties by name) and take the smallest, the median (the lower median, position (m - 1) // 2 of
m datasets) and the largest.

Pilot content: all 12 C0 searchers; the six baselines (random forest with 3 model seeds); C1, C2 and C3
on ga, bpso_S, de_S and gwo_S at the middle grid values P = 5, lambda = 1, r = 4; repeat 0 only;
outer folds 0-4; search seed index 0; budget 2,000.
"""

import csv
import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
OUT = REPO_ROOT / "configs" / "pilot.yaml"


def main():
    dev = [l.strip() for l in (REPO_ROOT / "data/split/development.txt").read_text(encoding="utf-8").splitlines()
           if l.strip()]
    rules = json.loads((REPO_ROOT / "data/meta/data_handling_rules.json").read_text(encoding="utf-8"))
    with open(REPO_ROOT / "data/meta/audit.csv", encoding="utf-8", newline="") as f:
        audit = {r["dataset"]: r for r in csv.DictReader(f)}
    drop_cols = {d: len(v["columns"]) for d, v in rules.get("drop_columns", {}).items()}
    dup = set(rules.get("drop_duplicate_rows", {}))
    rows = []
    for d in dev:
        n = int(audit[d]["n_samples"]) - (int(audit[d]["n_exact_duplicate_rows_with_target"]) if d in dup else 0)
        p = int(audit[d]["n_features"]) - drop_cols.get(d, 0)
        rows.append((n * min(200, p), d, n, p))
    rows.sort()
    m = len(rows)
    chosen = {"smallest": rows[0], "median": rows[(m - 1) // 2], "largest": rows[-1]}
    lines = [
        "# Pilot plan (PREREG_STAGE1 section 10; part 6b). Generated by src/make_pilot_plan.py from metadata only.",
        "# Datasets: the smallest, the (lower) median and the largest development dataset by",
        "# n_samples x min(200, n_features), with n and p after the data-handling rules:",
    ]
    for label, (score, d, n, p) in chosen.items():
        lines.append(f"#   {label:<8} {d}: n = {n}, p = {p}, score = {score}")
    lines.append("# All development datasets by score: " + ", ".join(f"{d} ({s})" for s, d, _, _ in rows))
    lines += [
        "name: pilot",
        "group: development",
        "datasets:",
        *[f"  - {chosen[k][1]}" for k in ("smallest", "median", "largest")],
        "repeats: [0]",
        "folds: [0, 1, 2, 3, 4]",
        "search_seed_indices: [0]",
        "budget: 2000",
        "c0_searchers: [random, hill_climb, one_plus_one, ga, bpso_S, bpso_V, de_S, de_V, gwo_S, gwo_V, woa_S, woa_V]",
        "control_searchers: [ga, bpso_S, de_S, gwo_S]",
        "controls:",
        "  C1: 5      # P (patience)",
        "  C2: 1.0    # lambda",
        "  C3: 4      # r (neighbours)",
        "baselines: [all_k, l1, enet, ftest, mrmr, rf]",
        "rf_model_seed_indices: [0, 1, 2]",
        "",
    ]
    OUT.parent.mkdir(exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print("\n".join(lines[:5]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
