"""Write configs/confirmation.yaml (core tier) and configs/confirmation_s2.yaml from metadata only.

    python src/make_confirmation_plans.py

Reads data/split/confirmation.txt, data/meta/audit.csv and data/meta/data_handling_rules.json (via
estimate_compute.dataset_sizes); never opens a parquet file. Prints counts only, never dataset names.

Core tier (stage-2 choices, results/stage2/stage2_choices.json): the 31 confirmation datasets; repeats 0-1
x folds 0-4 (10 outer folds); search seed indices 0-2; budget 2,000; the 12 C0 configurations (C4 logged
in-run); C1 (P = 5), C2 (lambda = 1), C3 (r = 8) on ga, bpso_S, de_S, gwo_S; baselines all_k, l1, enet
(max_iter 10000 in src/fsbench/baselines.py), ftest, mrmr, rf (model seed indices 0-2).
S2 (PREREG_STAGE1 section 11): ga C0 (C4 logged) and l1 with prefilter: false, same folds and seeds, on
the confirmation datasets with p <= 1000, p = n_features after the data-handling rules.
"""

import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT / "src"))
import estimate_compute as ec  # noqa: E402

S2_MAX_P = 1000
COMMON = ["repeats: [0, 1]", "folds: [0, 1, 2, 3, 4]", "search_seed_indices: [0, 1, 2]", "budget: 2000"]


def write(path, lines):
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")


def main():
    names = [l.strip() for l in (REPO_ROOT / "data/split/confirmation.txt").read_text(encoding="utf-8").splitlines()
             if l.strip()]
    sizes = ec.dataset_sizes()
    assert len(names) == 31 and all(sizes[d][0] == "confirmation" for d in names)
    s2 = [d for d in names if sizes[d][2] <= S2_MAX_P]

    write(REPO_ROOT / "configs/confirmation.yaml", [
        "# Confirmation plan, core tier (stage-2 choices: P = 5, lambda = 1, r = 8; C4 logged in every C0 run).",
        "# Generated by src/make_confirmation_plans.py from metadata only.",
        "name: confirmation", "group: confirmation", "datasets:", *[f"  - {d}" for d in names], *COMMON,
        "c0_searchers: [random, hill_climb, one_plus_one, ga, bpso_S, bpso_V, de_S, de_V, gwo_S, gwo_V, woa_S, woa_V]",
        "control_searchers: [ga, bpso_S, de_S, gwo_S]", "controls:", "  C1: 5      # P", "  C2: 1.0    # lambda",
        "  C3: 8      # r", "baselines: [all_k, l1, enet, ftest, mrmr, rf]", "rf_model_seed_indices: [0, 1, 2]",
        "prefilter: true",
    ])
    write(REPO_ROOT / "configs/confirmation_s2.yaml", [
        "# Sensitivity analysis S2 (PREREG_STAGE1 section 11): the H3 comparison (ga + C4 vs L1 logistic regression)",
        f"# without the pre-filter, on confirmation datasets with p <= {S2_MAX_P} after the data-handling rules.",
        "# Generated by src/make_confirmation_plans.py from metadata only.",
        "name: confirmation_s2", "group: confirmation", "datasets:", *[f"  - {d}" for d in s2], *COMMON,
        "c0_searchers: [ga]", "control_searchers: []", "controls: {}", "baselines: [l1]", "prefilter: false",
    ])
    print(f"confirmation datasets: {len(names)}; qualifying for S2 (p <= {S2_MAX_P}): {len(s2)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
